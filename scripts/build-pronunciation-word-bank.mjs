import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";

const root = process.cwd();
const seedPath = path.join(root, "src/domain/pronunciation/word-bank-seed.ts");
const dictionaryPath = path.join(root, "vendor/cmudict/cmudict-0.7b.dict");
const outputPath = path.join(
  root,
  "src/domain/pronunciation/word-bank.generated.ts",
);

const soundArpabet = {
  light_l: "L",
  s: "S",
  f: "F",
  v: "V",
  z: "Z",
};
const difficulties = ["easy", "medium", "hard"];

function readSeeds() {
  const source = readFileSync(seedPath, "utf8");
  const match = /export const PRONUNCIATION_WORD_BANK_SEEDS\s*=\s*(\{[\s\S]*\})\s*as const;/u.exec(
    source,
  );
  if (!match) throw new Error("Could not read pronunciation word-bank seeds.");
  return Function(`"use strict"; return (${match[1]});`)();
}

function parseDictionary(source) {
  return source
    .split(/\r?\n/u)
    .flatMap((line) => {
      const trimmed = line.trim();
      if (!trimmed || trimmed.startsWith(";;;")) return [];
      const match = /^(\S+?)(?:\((\d+)\))?\s+(.+)$/u.exec(trimmed);
      if (!match) return [];
      return [
        {
          word: match[1].toLocaleLowerCase("en-US"),
          cmuVariant: Number(match[2] ?? 1),
          phones: match[3].split(/\s+/u),
        },
      ];
    });
}

function basePhone(phone) {
  return phone.replace(/[012]$/u, "");
}

function isVowel(phone) {
  return /^[A-Z]+[012]$/u.test(phone);
}

function targetPhoneIndex(phones, soundId) {
  const indexes = phones.flatMap((phone, index) =>
    basePhone(phone) === soundArpabet[soundId] ? [index] : [],
  );
  if (indexes.length !== 1) return null;
  const index = indexes[0];
  if (soundId === "light_l" && (!phones[index + 1] || !isVowel(phones[index + 1]))) {
    return null;
  }
  return index;
}

function parseSeed(seed) {
  const [text, targetLetters] = seed.split("|");
  if (!text || !targetLetters) throw new Error(`Invalid seed: ${seed}`);
  const normalizedText = text.toLocaleLowerCase("en-US");
  const highlightStart = normalizedText.indexOf(targetLetters.toLocaleLowerCase("en-US"));
  if (highlightStart < 0) {
    throw new Error(`Highlight is not in word: ${seed}`);
  }
  return {
    text: normalizedText,
    targetLetters: targetLetters.toLocaleLowerCase("en-US"),
    highlightStart,
    highlightLength: targetLetters.length,
  };
}

function buildBank(seeds, dictionary) {
  const entries = [];
  for (const [soundId, groups] of Object.entries(seeds)) {
    for (const difficulty of difficulties) {
      const words = groups[difficulty];
      if (!Array.isArray(words) || words.length !== 10) {
        throw new Error(`${soundId}/${difficulty} must contain exactly ten words.`);
      }
      for (const seed of words) {
        const parsedSeed = parseSeed(seed);
        const candidates = dictionary
          .filter((entry) => entry.word === parsedSeed.text)
          .map((entry) => ({
            entry,
            targetPhoneIndex: targetPhoneIndex(entry.phones, soundId),
          }))
          .filter((candidate) => candidate.targetPhoneIndex !== null);
        if (candidates.length === 0) {
          throw new Error(`No verified pronunciation for ${soundId}: ${seed}`);
        }
        const chosen = candidates[0];
        entries.push({
          soundId,
          difficulty,
          ...parsedSeed,
          targetArpabet: soundArpabet[soundId],
          phones: chosen.entry.phones,
          targetPhoneIndex: chosen.targetPhoneIndex,
          cmuVariant: chosen.entry.cmuVariant,
        });
      }
    }
  }
  if (entries.length !== 150) throw new Error("Pronunciation word bank must contain 150 words.");
  return entries;
}

const dictionary = parseDictionary(readFileSync(dictionaryPath, "utf8"));
const entries = buildBank(readSeeds(), dictionary);
const generated = `// Generated by scripts/build-pronunciation-word-bank.mjs.\n\nimport type { PracticeDifficulty, PracticeSoundId } from "@/domain/pronunciation/practice";\n\nexport type PronunciationWordBankEntry = {\n  soundId: PracticeSoundId;\n  difficulty: PracticeDifficulty;\n  text: string;\n  targetLetters: string;\n  highlightStart: number;\n  highlightLength: number;\n  targetArpabet: string;\n  phones: string[];\n  targetPhoneIndex: number;\n  cmuVariant: number;\n};\n\nexport const PRONUNCIATION_WORD_BANK: readonly PronunciationWordBankEntry[] = ${JSON.stringify(entries, null, 2)};\n`;

writeFileSync(outputPath, generated);
console.log(`Wrote ${entries.length} pronunciation word-bank entries.`);
